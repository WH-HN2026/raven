#!/usr/bin/env bash
# Per-worktree dev environment (AGENTS.md "Parallel worktrees"). Writes
# .env.local with:
#   - a per-worktree database raven_<slug> on the shared raven-db (127.0.0.1:5433),
#     created if missing (needs `make infra-up` first);
#   - free ports for the Go server and Vite (kept on re-runs);
#   - the shared Dojo URL/credentials and the app's bootstrap admin.
# Idempotent: re-running keeps the ports and the database.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

shared="$(scripts/shared-env.sh)"
set -a; . "$shared"; set +a

branch="$(git rev-parse --abbrev-ref HEAD)"
slug="$(echo "${branch#t/}" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9\n' '_' | cut -c1-40)"
db="raven_${slug}"

# ── database ──
if ! docker compose exec -T raven-db pg_isready -U raven -d raven >/dev/null 2>&1; then
  echo "raven-db is not running: run 'make infra-up' first" >&2
  exit 1
fi
exists="$(docker compose exec -T raven-db psql -U raven -d raven -tAc "SELECT 1 FROM pg_database WHERE datname = '$db'")"
if [[ "$exists" != "1" ]]; then
  docker compose exec -T raven-db psql -U raven -d raven -qc "CREATE DATABASE \"$db\""
  echo "created database $db"
fi

# ── ports ──
port_free() { ! ss -ltnH "sport = :$1" | grep -q .; }
pick_port() { # pick_port <base> <exclude>
  local p=$1
  while ! port_free "$p" || [[ "$p" == "${2:-}" ]]; do p=$((p + 1)); done
  echo "$p"
}
http_port=""; vite_port=""
if [[ -f .env.local ]]; then
  http_port="$(sed -n 's/^RAVEN_HTTP_PORT=//p' .env.local)"
  vite_port="$(sed -n 's/^RAVEN_VITE_PORT=//p' .env.local)"
fi
# Spread worktrees over the range by a hash of the slug, then probe upwards.
offset=$(( $(echo -n "$slug" | cksum | cut -d' ' -f1) % 400 * 2 ))
[[ -n "$http_port" ]] || http_port="$(pick_port $((18000 + offset)))"
[[ -n "$vite_port" ]] || vite_port="$(pick_port $((19000 + offset)) "$http_port")"

umask 077
cat > .env.local <<EOF
# Generated by scripts/wt-env.sh for branch $branch. Do not commit.
RAVEN_HTTP_PORT=$http_port
RAVEN_HTTP_ADDR=127.0.0.1:$http_port
RAVEN_VITE_PORT=$vite_port
RAVEN_DATABASE_URL=postgres://raven:$RAVEN_DB_PASSWORD@127.0.0.1:${RAVEN_DB_PORT:-5433}/$db?sslmode=disable
RAVEN_ENCRYPTION_KEY=$RAVEN_ENCRYPTION_KEY
RAVEN_ADMIN_USERNAME=${RAVEN_ADMIN_USERNAME:-admin}
RAVEN_ADMIN_PASSWORD=$RAVEN_ADMIN_PASSWORD
RAVEN_DOJO_URL=http://localhost:${DD_PORT:-18080}
RAVEN_DOJO_TOKEN=${RAVEN_DOJO_TOKEN:-}
RAVEN_DOJO_ORGANIZATION=${RAVEN_DOJO_ORGANIZATION:-RAVEN}
DD_ADMIN_USER=${DD_ADMIN_USER:-admin}
DD_ADMIN_PASSWORD=$DD_ADMIN_PASSWORD
EOF

cat <<EOF
.env.local written for $branch
  database : $db on 127.0.0.1:${RAVEN_DB_PORT:-5433}
  API      : http://127.0.0.1:$http_port/api/healthz
  UI (Vite): http://127.0.0.1:$vite_port      ← open this after 'make dev'
  DefectDojo: http://localhost:${DD_PORT:-18080}
  login    : ${RAVEN_ADMIN_USERNAME:-admin} / see RAVEN_ADMIN_PASSWORD in .env.local
EOF
